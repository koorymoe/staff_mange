import { describe, it, expect } from 'vitest'
import { trUR } from './translateDom'

// (دازاي 11-13) «نص عربي ونص باكستاني» — النصوص الي بيها أرقام وتواريخ تتترجم كاملة
describe('trUR patterns', () => {
  it('dates and counts', () => {
    expect(trUR('الجمعة، ١٣ تشرين الثاني، من ٠١:٣٢ م إلى ٠٢:٣٢ م')).toBe('جمعہ، ١٣ نومبر، ٠١:٣٢ م سے ٠٢:٣٢ م تک')
    expect(trUR('الجمعة، ١٣ تشرين الثاني ٢٠٢٦')).toBe('جمعہ، ١٣ نومبر ٢٠٢٦')
    expect(trUR('بانتظار الرفع (67)')).toBe('اپلوڈ کا انتظار (67)')
    expect(trUR('السرعة 3 من ٥')).toBe('رفتار ٥ میں سے 3')
    expect(trUR('عندك 2 حجوزات اليوم، 30 حجوزات ناقصها فاتورة أو تقرير. كمّل شغلك أول.')).toBe('آپ کے پاس 2 آج کی بکنگ، 30 بکنگ جن کا بل یا رپورٹ باقی ہے ہیں۔ پہلے اپنا کام مکمل کریں۔')
    expect(trUR('حجز B1 · الانطلاق والطريق: ما صارت ووقتها فات — ما صارت لحد هسه. صارلها 1 يوم 23 س تنتظر، والمعتاد ما يتجاوز 30 د.')).toBe('بکنگ B1 · روانگی اور راستہ: نہیں ہوا اور وقت گزر گیا — ابھی تک نہیں ہوا۔ 1 دن 23 گھنٹے سے انتظار، عام طور پر 30 منٹ سے زیادہ نہیں۔')
  })
})
