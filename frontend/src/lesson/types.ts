// ═══ الدرس قبل التطبيق ═══
//
// «أول شي نفصل الخطوات والدروس عن التطبيق العملي — كل تجربة يشوفون
// شرح عليها وبعدها يطبقونه، ومن يطبقون غلط يطلعلهم الغلط وين».
//
// ⚠️⚠️ **الفصل هو الفكرة نفسها.** محاكي بلا شرح يعلّم بالتخمين:
// المتدرّب يحرّك أشياء لحد ما تصير خضراء، ويطلع يعرف **شنو** ضغط
// ولا يعرف **ليش**. وأول موقف حقيقي ما يشبه التمرين يوگف.
//
// ⚠️⚠️ وأهم قطعة هنا هي **الثالثة**: الغلط يرجع لخطوة الدرس الي
// شرحته. «فشل الفحص» لحاله ما يعلّم شي — «هذا الي شرحناه بالخطوة ٣»
// يسكّر الحلقة بين ما قراه وما سواه.

import type { DomainId } from '../lab/types'

export interface LessonStep {
  title: string
  /** الشرح — فقرة أو فقرتان، بلغة الميدان مو بلغة الكتاب. */
  body: string
  /** شنو يسوي المتدرّب بهالخطوة وقت التطبيق. */
  todo?: string
  /**
   * ⚠️ نمط يطابق **رسالة المحرّك** لمن يغلط بهالخطوة تحديداً.
   * هذا الي يربط الغلط بالشرح.
   *
   * ⚠️ ولازم يكون **دقيقاً**: نمط واسع يخطف أخطاء خطوات ثانية،
   * فيوجّه المتدرّب للشرح الغلط — وهذا أسوأ من ما نوجّهه أصلاً،
   * لأنه يقرا فقرة ما إلها علاقة ويرجع أضيع.
   */
  catch?: string
}

export interface Pitfall {
  /** شنو يشوفه الفني بالميدان. */
  symptom: string
  /** السبب الحقيقي. */
  cause: string
}

export interface Lesson {
  id: string
  domain: DomainId
  title: string
  /** سطر واحد يظهر بالبطاقة. */
  summary: string
  minutes: number
  /** ⚠️ **ليش** هالدرس مهم بشغل الشركة — بلاها الدرس معلومة عامة. */
  why: string
  steps: LessonStep[]
  pitfalls: Pitfall[]
  /** المطلوب بالتطبيق — يبقى معروضاً طول التمرين. */
  task: string
  /** تلميحات تظهر لمن يطلبها المتدرّب. */
  hints: string[]
}

/** ═══ ربط الغلط بالخطوة ═══
 *
 * ⚠️ الرسالة الي **ما تطابق** أي خطوة تبقى ظاهرة كخطأ عادي — ما
 * ننسبها لأقرب خطوة. نسبة غلط لخطوة ما تخصّها تخلّي المتدرّب يعيد
 * قراءة شرح صحيح وهو يدوّر على غلط بمكان ثانٍ.
 */
export function stepForError(lesson: Lesson, text: string): number | null {
  for (let i = 0; i < lesson.steps.length; i++) {
    const c = lesson.steps[i].catch
    if (c && new RegExp(c).test(text)) return i
  }
  return null
}
