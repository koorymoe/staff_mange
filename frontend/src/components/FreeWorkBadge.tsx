/* ═══ شريحة «الشغل مجاني» ═══
 *
 * (ع): «من تروح للمحاسب حددها فاتورة مجانية».
 *
 * 🔴 المجانية چانت **مخفية تماماً** عن المحاسب والمراقب: الليدر
 * يأشّرها بسببها، والخادم يخلي الكلفة الحقيقية ويحطّ الخصم = الكلفة
 * كلها والصافي صفر — فالي يوصل المحاسب هو **صافي صفر وخصم كامل**،
 * يعني شكلها فاتورة أحد فضّاها، مو ضماناً موثَّقاً.
 *
 * فكانت النتيجة إنه يأشّرها «غير مطابق» فتنفتح مخالفة على شغل سليم.
 *
 * ⚠️ مكوّن واحد بكل الشاشات (نفس مبدأ StatTile وPageHeader): الشريحة
 * لازم تقرا نفس الشي بفواتير الليدر وبالتدقيق اليومي وبتدقيق
 * الحسابات — وإلا المحاسب يشوف صيغتين لنفس الحالة ويشك بالاثنتين.
 */
type Props = {
  /** ما يُعرض شي لمّا تكون false — حتى ما يحتاج كل نداء يغلّفها بشرط */
  isFree?: boolean | null
  /** اسم السبب من سجل أسباب المجانية (ضمان · إعادة عمل · …) */
  reason?: string | null
  note?: string | null
  className?: string
}

export default function FreeWorkBadge({ isFree, reason, note, className = '' }: Props) {
  if (!isFree) return null
  // 🔴 «رقم غلط أسوأ من ماكو رقم» — ونفس الشي بالسبب: فاتورة مجانية
  // بلا سبب مسجَّل تقرا «مجاني — بلا سبب مسجَّل» صريحة، مو شريحة
  // ناقصة تخلي المحاسب يحسب إن السبب موجود وهو ما شافه.
  const label = reason && reason.trim() !== '' ? reason : 'بلا سبب مسجَّل'
  return (
    <span
      title={note && note.trim() !== '' ? note : undefined}
      className={`inline-flex items-center gap-1 rounded-full bg-emerald-100 px-2 py-0.5 text-[11px] font-bold text-emerald-800 ${className}`}
    >
      🎁 مجاني — {label}
    </span>
  )
}
