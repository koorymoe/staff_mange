package repository

import (
	"math"
	"testing"

	"staffmange-api/internal/model"
)

// ═══ حارس: المجموع يطابق الشيت ═══
//
// ثالث اختبار طلبه (ع). والعلّة الي يحرسها **صارت فعلاً بهذي
// الجلسة**: عرض سعر بخصم ١٠٪ بقى صافيه ٨٨٠٬٠٠٠ لمن انتغيّر الخصم
// وحده، لأن التعديل ماكان يعيد الحساب من البنود (`6dd7252`).
//
// ⚠️ **بلا قاعدة بيانات بقصد**: الحساب دالة خالصة، والاختبار الي
// يحتاج قاعدة ما ينشغّل بكل مرة — وهذا الي خلّى العلل تعيش.
func TestTotalsMatchSheet(t *testing.T) {
	eq := func(name string, got, want float64) {
		// ⚠️ مقارنة بهامش: `float64` ما يخزّن الكسور العشرية بدقة،
		// و`==` على الفلوت يفشل عشوائياً بأرقام صحيحة تماماً.
		if math.Abs(got-want) > 0.005 {
			t.Fatalf("%s: انتظرنا %.2f ولگينا %.2f", name, want, got)
		}
	}

	// ① الحالة الأساسية: كمية × سعر، مجموعة على البنود.
	items := []model.QuotationItemInput{
		{Quantity: 3, UnitPrice: 250000},
		{Quantity: 2, UnitPrice: 125000},
	}
	g, d, n := computeTotals(items, 0)
	eq("المجموع بلا خصم", g, 1000000)
	eq("قيمة الخصم", d, 0)
	eq("الصافي", n, 1000000)

	// ② الخصم ينحسب من المجموع — ونفس المثال الي انكسر فعلاً.
	g, d, n = computeTotals(items, 10)
	eq("المجموع مع خصم ١٠٪", g, 1000000)
	eq("قيمة خصم ١٠٪", d, 100000)
	eq("الصافي بعد ١٠٪", n, 900000)
	// 🔴 هاي السطر هو الحارس الحقيقي: الصافي **لازم** يطابق
	// المجموع ناقص الخصم — مو رقماً محفوظاً من حساب أقدم.
	eq("الصافي = المجموع − الخصم", n, g-d)

	// ③ قائمة فاضية: أصفار مو أخطاء — الشيت الفاضي مجموعه صفر.
	g, d, n = computeTotals(nil, 15)
	eq("مجموع الفاضي", g, 0)
	eq("خصم الفاضي", d, 0)
	eq("صافي الفاضي", n, 0)

	// ④ سعر كسري: «١.٥» تعني ألف ونص بقرار (ع)، والتوسيع يصير
	// بالواجهة — فالحساب هنا لازم يمرّر الكسر كما هو بلا تقريب.
	g, _, n = computeTotals([]model.QuotationItemInput{{Quantity: 2, UnitPrice: 1500.5}}, 0)
	eq("سعر كسري × كمية", g, 3001)
	eq("صافي السعر الكسري", n, 3001)

	// ⑤ خصم ١٠٠٪: الصافي صفر مو سالب.
	_, d, n = computeTotals(items, 100)
	eq("خصم كامل", d, 1000000)
	eq("صافي الخصم الكامل", n, 0)
}
