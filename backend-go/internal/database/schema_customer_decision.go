// والإرجاع والبحث يشتغلون على الحالتين بلا سطر زيادة.
//
// ⚠️ **نص مو enum**: إضافة قيمة لـenum ما تنفع بنفس المعاملة الي
// أنشأته، وهاي علّة انعضّينا منها قبل. والقيم محصورة بالكود.
//
// ⚠️ **NULL = «ما رد»**: كل الصفوف القديمة انحطّت بالانتظار لأن
// الزبون ما رد (ماكان أكو سبب ثاني)، فالافتراضي لازم يكون هو —
// وإلا حجوزات قديمة تنقلب «بانتظار موافقة الزبون» وهي مو هيچ.

