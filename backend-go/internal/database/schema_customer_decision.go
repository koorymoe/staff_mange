// ═══ «الزبون يرجع خبر» — انتظار قراره ═══
//
// (ع): «الزبون يستفسر وبعدين يرجع خبر — الحجز ينتقل إلى خانة اسمها
// بانتظار موافقة الزبون».
//
// 🔴 **ليش عمود مميّز مو حالة جديدة**: آلية الانتظار موجودة كاملة
