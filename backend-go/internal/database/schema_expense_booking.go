package database

// ═══ المصروف ينربط بحجزه ═══
//
// ⚠️⚠️ **الشاشة چانت تحسب غلط.** `Finance.tsx` چان ينسب المصاريف
// **بالموظف مو بالحجز**: كل مصاريف الليدر المعتمدة تنحسب على **كل
// حجز** هو مسؤول عنه. ليدر عنده ١٠ حجوزات ومصروف واحد بـ٥٠ ألف ←
// المصروف ينحسب **١٠ مرات**، فيطلع «نقص» بحجوزات مبالغها سليمة —
// والمحاسب يدوّر على فلوس ما ضاعت.
//
// والسبب الجذري إن الجدول **ماكو بيه ربط بالحجز أصلاً**: موظف ومبلغ
// ووصف وحالة وتاريخ، وبس. فالنسبة چانت تخميناً مبنياً على «منو
// المسؤول عن مصاريف الحجز».
//
// ⚠️⚠️ **ترحيل مستقل مو تعديل `CREATE TABLE`**: الجدول موجود بقاعدة
// الإنتاج، و`CREATE TABLE IF NOT EXISTS` **ما تسوي شي** عليها. تعديل
// التعريف وحده يعني كوداً يقرا عموداً مو موجود بالإنتاج — والصفحة
// تنهار بأول استعلام.
//
// ⚠️ **والعمود nullable**: المصاريف القديمة ما إلها حجز. جعله
// إجبارياً يعني ترحيلاً يفشل، أو أسوأ: صفوفاً تنكتب بحجز مخترَع.
// والقديمة تنعرض بجدول منفصل «ما تنحسب» — تظهر ولا تكذب.
//
// ⚠️ و`ON DELETE SET NULL` مو `CASCADE`: حذف حجز ما يصير يمحي **سجل
// صرف فلوس**. المصروف صار فعلاً والفلوس انصرفت.
