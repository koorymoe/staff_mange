//
// جدول بنود عرض السعر ما بيه عمود للصورة. فالصورة تنعرض وانت تكتب
// العرض (تجي من كتالوك المنتجات)، وأول ما تحفظ وتفتحه من جديد —
// تختفي. والعرض ينطبع للزبون بمربعات فاضية.
//
// نخزن **المرجع** مو الصورة نفسها: القيمة إما مسار ملف
// (/api/files/xxx) أو data: URL قديمة — نفس ما يخزنه المنتج بالضبط.
// تخزين البايتات هنا يكرر نفس الصورة بكل عرض ويكبّر القاعدة بلا فايدة.
//
// وليش ننسخها أصلاً بدل ما نجيبها من المنتج وقت العرض؟ لأن العرض
// وثيقة انرسلت للزبون بتاريخ معيّن. لو تغيّرت صورة المنتج بعدين،
// العرض القديم لازم يبقى مثل ما انرسل.
func quotationImageMigration() []Migration {
	return []Migration{
		{
			Version: "0232_quotation_item_image",
			SQL: `
				ALTER TABLE "QuotationItem"
					ADD COLUMN IF NOT EXISTS "imageBase64" TEXT;
			`,
		},
	}
}
