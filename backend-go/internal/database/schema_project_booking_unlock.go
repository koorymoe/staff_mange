//
// هذا العمود هو الخيط: أول ما مدير المشاريع يوصل المشروع لمرحلة
// «٥. البدء بالتنفيذ» ينكتب الوقت، فينفتح الحجز عند المنسّق وينتسّق
// مثل أي حجز عادي. وقبله يضل ظاهر عنده **مقفول** — يشوفه ويعرف وين
// وصل، بس ما يكدر يلمسه.
//
// ⚠️ ليش وقت مو boolean؟ لأن «متى انفتح» سؤال ينسأل: كم قعد المشروع
// بالإجراءات قبل ما يوصل التنفيذ. الـboolean يرمي هالمعلومة.
