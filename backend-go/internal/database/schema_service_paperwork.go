// ═══ الورق على مسؤول الخدمة ═══
//
// اكو حجوزات ما تستدعي فريقاً كاملاً — الجي بي اس والداش كام، والاثنان
// ينربطون بسيارة أو دراجة. يروح فني واحد وينصّب، وبعدها مطلوب تقرير
// وفاتورة. وصاحب العمل قرر: **الفني ما يسوي الورق بهالخدمات** —
// مسؤول الخدمة نفسه يسويه بداله.
//
// ⚠️⚠️ **علم مستقل ومو استعمال `requiresDeviceInfo` الموجود.** ذاك
// معناه «اطلب عدد الأجهزة ونوع المركبة وقت الحجز» — معنى ثاني تماماً.
// لو حمّلناه معنيين، أول خدمة جديدة تحتاج بيانات أجهزة **تاخذ قاعدة
// الورق بالصدفة**، ومسؤولها ما يعرف ليش صار مسؤولاً عن ورق ما طلبه
// أحد. علمان منفصلان = معنيان منفصلان.
//
// ⚠️⚠️ **وماكو أسماء خدمات بالكود.** النظام عنده أصلاً
// `services.find(s => s.name === 'GPS')` بـ`Layout.tsx`، وهاي بالضبط
// الي ننكوى بيها: أول ما يتغيّر اسم الخدمة بحرف تنطفي الميزة بصمت
// وبلا رسالة خطأ. الاسم بيانات، والقاعدة بيانات — والكود يقرا العلم
// بس. صاحب العمل يأشّر الخدمات من شاشة «مسؤولو الخدمات».
//
// ⚠️ والافتراضي `false`: كل الخدمات الموجودة تبقى تشتغل **حرفياً مثل
// اليوم** لحد ما يأشّر واحدة بيده. ترحيل يأشّر خدمات لحاله يغيّر شغل
