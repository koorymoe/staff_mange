// Package safeguard يحمي المهام الخلفية من إسقاط السيرفر كله.
//
// ═══ ليش هذا الملف موجود ═══
//
// بلغة Go، الـpanic الي ما ينمسك بـrecover **بأي goroutine** يقتل
// العملية كلها — مو بس ذاك الـgoroutine.
//
// middleware.Recovery يحمي طلبات HTTP بس، لأنه يلتف حول معالج الطلب.
// أما الكنسات الدورية (تذكير الحجوزات، الانضباط) فتشتغل بـgoroutines
// منفصلة، وما يوصلها ذاك الحماية إطلاقاً.
//
// النتيجة الي كانت تصير بالإنتاج: كنسة تشتغل كل ساعة، تصادف صف بيانات
// ناقص (حجز بلا زبون، موعد فاضي)، تسوي nil dereference → panic →
// **السيرفر كله يموت**. دوكر يعيد تشغيله بعد ثواني، بس بهاي الفترة كل
// موظف على كل شاشة يشوف «Failed to fetch» — لأن الطلب ما لگه سيرفر
// أصلاً، فما وصله رد HTTP ولا رسالة خطأ مفهومة.
//
// وهذا يفسّر ليش الخطأ كان يطلع بأماكن ما إلها علاقة ببعض: المشكلة ما
// كانت بالزر الي ينضغط، كانت بالسيرفر الي ينهار تحته.
package safeguard

import (
	"log"
	"runtime/debug"
	"time"
)

// Go يشغّل مهمة خلفية بحماية. أي panic ينمسك وينسجّل ويضل السيرفر واقف.
//
// name يطلع باللوگ حتى نعرف أي مهمة انهارت بلا تخمين.
func Go(name string, fn func()) {
	go Run(name, fn)
}

// Run ينفّذ fn بنفس الحماية بلا goroutine جديد — للاستدعاء من جوّا حلقة.
//
// يرجع true إذا خلصت بسلام، false إذا انهارت.
func Run(name string, fn func()) (ok bool) {
	defer func() {
		if err := recover(); err != nil {
			ok = false
			log.Printf("[safeguard] ⚠️ المهمة الخلفية «%s» انهارت (السيرفر بخير): %v\n%s",
				name, err, debug.Stack())
		}
	}()
	fn()
	return true
}

// Loop يشغّل مهمة دورية للأبد بحماية.
//
//   - delay: تأخير أولي حتى ما تزاحم إقلاع السيرفر
//   - every: الفاصل بين الدورات
//
// الانهيار بدورة وحدة ما يوگف الحلقة — الدورة الجاية تشتغل بوقتها.
// مهمة خلفية تموت بصمت أسوأ من وحدة تنهار وتكمل، لأن الأولى تخلي
// التذكيرات توقف بلا ما ينتبه أحد.
func Loop(name string, delay, every time.Duration, fn func()) {
	go func() {
		time.Sleep(delay)
		for {
			Run(name, fn)
			time.Sleep(every)
		}
	}()
}
