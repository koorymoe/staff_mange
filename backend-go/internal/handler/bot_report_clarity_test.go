package handler

import "testing"

func TestBotBodyClear(t *testing.T) {
	for _, c := range []struct {
		body string
		ok   bool
	}{
		{"Ggggg تجريبي جدا جدا جدا لازم", false},                     // البلاغ #5 الي عبر قبل
		{"ههههههه ههههه خربانة خربانة خربانة خربانة", false},           // تكرار
		{"!!!!! ???? 12345 6789 0000 ....", false},                   // رموز وأرقام
		{"خربانة", false},                                             // قصير
		{"بشاشة الفواتير من أضغط حفظ يطلع خطأ وما تنحفظ", true},        // واضح
		{"من افتح الاعدادات بلموبايل هيج تطلعلي النتيجه", true},        // البلاغ #9 الحقيقي
		{"تجريبي للبوت بس نريد نجربه اليوم", true},                     // تجربة دازاي تبقى مسموحة
		{"شاشة المخازن زر تسليم الأدوات يطلع خطأ 500 وما يتسجل", true}, // ويا رقم
	} {
		if got := botBodyClear(c.body); got != c.ok {
			t.Errorf("%q: طلع %v، المتوقع %v", c.body, got, c.ok)
		}
	}
}
